-- Public/read-only reference access for the simulation. Writes require a role.
do $$
declare t text; begin
  foreach t in array array['wards','standards_topics','compliance_scores','planned_audits','unplanned_audits','pending_audits','action_plans','audit_tools','references_library','reports','report_references','report_status_history','qi_projects','training_resources','courses','liaisons'] loop
    execute format('drop policy if exists viewer_read on public.%I', t);
    execute format('create policy viewer_read on public.%I for select using (true)', t);
  end loop;
end $$;

-- Limited public verification only: name, course and issue date through the view.
create or replace view public.public_certificate_verification as
select c.number, c.trainee_name, co.name as course_name, c.issued_on
from public.certificates c join public.courses co on co.id = c.course_id;
grant select on public.public_certificate_verification to anon, authenticated;

-- Exam questions are readable only to authenticated application roles; correct_index is
-- still blocked from the browser by using score_exam for production scoring.
drop policy if exists course_read on public.courses;
create policy course_read on public.courses for select using (true);
drop policy if exists question_read_authenticated on public.exam_questions;
create policy question_read_authenticated on public.exam_questions for select to authenticated using (true);

-- Role-based writes.
do $$
declare t text; begin
  foreach t in array array['planned_audits','unplanned_audits','pending_audits','action_plans','reports','report_references','report_status_history','qi_projects','exam_attempts'] loop
    execute format('drop policy if exists auditor_write on public.%I', t);
    execute format('create policy auditor_write on public.%I for all to authenticated using (public.is_admin_or_auditor()) with check (public.is_admin_or_auditor())', t);
  end loop;
  foreach t in array array['wards','standards_topics','compliance_scores','audit_tools','references_library','training_resources','courses','exam_questions','certificates','liaisons','user_roles'] loop
    execute format('drop policy if exists admin_write on public.%I', t);
    execute format('create policy admin_write on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $$;

