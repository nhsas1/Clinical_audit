-- Answers are never exposed through a view or client-readable policy.
create or replace function public.score_exam(p_course_id uuid, p_answers jsonb, p_trainee_name text, p_ward_id uuid default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare total integer; correct integer; result_score numeric(5,2); did_pass boolean; attempt_id uuid; cert_no text;
begin
  if p_trainee_name is null or length(trim(p_trainee_name)) < 2 then raise exception 'Trainee name is required'; end if;
  select count(*) into total from public.exam_questions where course_id = p_course_id;
  if total = 0 then raise exception 'Course has no questions'; end if;
  select count(*) into correct
  from public.exam_questions q
  where q.course_id = p_course_id
    and (p_answers ->> q.question_order::text) is not null
    and (p_answers ->> q.question_order::text)::integer = q.correct_index;
  result_score := round((correct::numeric / total::numeric) * 100, 2);
  select result_score >= pass_mark into did_pass from public.courses where id = p_course_id;
  insert into public.exam_attempts(course_id, trainee_name, ward_id, score, passed)
    values (p_course_id, trim(p_trainee_name), p_ward_id, result_score, did_pass) returning id into attempt_id;
  if did_pass then
    insert into public.certificates(number, attempt_id, trainee_name, course_id, score)
      values (public.next_certificate_number(), attempt_id, trim(p_trainee_name), p_course_id, result_score)
      returning number into cert_no;
  end if;
  return jsonb_build_object('attempt_id', attempt_id, 'score', result_score, 'passed', did_pass, 'certificate_number', cert_no);
end $$;

