-- Nursing Audit Hub — editable page text (Part B6)
-- Simulation only. Apply to a Supabase dev branch or dev project first.
-- Safe to run more than once.
--
-- site_content holds only the texts an admin has changed. A missing row means
-- "use the default written in the app", so "Reset to default" deletes the row.
-- Every insert, update and delete is copied to site_content_history.

begin;

create table if not exists public.site_content (
  key text primary key check (key ~ '^[a-z0-9._-]{1,120}$'),
  page text not null,
  value text not null check (length(value) between 1 and 2000),
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.site_content_history (
  id bigint generated by default as identity primary key,
  key text not null,
  page text not null,
  value text,               -- null when the text was reset to its default
  action text not null check (action in ('set', 'reset')),
  changed_by uuid references auth.users(id) on delete set null,
  changed_at timestamptz not null default now()
);
create index if not exists site_content_history_key_idx on public.site_content_history(key, changed_at desc);

-- Stamp the editor and keep the history, whoever writes.
create or replace function public.site_content_stamp()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    insert into public.site_content_history(key, page, value, action, changed_by) values (old.key, old.page, null, 'reset', auth.uid());
    return old;
  end if;
  new.updated_by := auth.uid();
  new.updated_at := now();
  insert into public.site_content_history(key, page, value, action, changed_by) values (new.key, new.page, new.value, 'set', auth.uid());
  return new;
end $$;
drop trigger if exists site_content_stamp on public.site_content;
create trigger site_content_stamp before insert or update or delete on public.site_content
  for each row execute function public.site_content_stamp();

alter table public.site_content enable row level security;
alter table public.site_content_history enable row level security;

-- Everyone (signed out too) reads the current text; only admins change it.
drop policy if exists content_read on public.site_content;
create policy content_read on public.site_content for select using (true);
drop policy if exists content_admin_write on public.site_content;
create policy content_admin_write on public.site_content for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- History is for admins only; rows are written by the trigger above.
drop policy if exists history_admin_read on public.site_content_history;
create policy history_admin_read on public.site_content_history for select to authenticated using (public.is_admin());

commit;
